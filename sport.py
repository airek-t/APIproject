def highest_score(point_gaurds, stat):
    top_shot_pct = 0
    for player in point_gaurds:
        if player[stat] > top_shot_pct:
            top_shot_pct = player[stat]
            best_shooter = player
    return best_shooter

def top_players(players, stat):
  player_one = highest_score(players, stat)
  players.remove(player_one)
  player_two = highest_score(players, stat)
  players.remove(player_two)
  player_three = highest_score(players, stat)
  top_three = [player_one, player_two, player_three]
  return top_three


